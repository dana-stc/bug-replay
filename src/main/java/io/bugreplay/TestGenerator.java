package io.bugreplay;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.Map;
import java.util.Set;

/** Turns a {@link Recording} into a JUnit 5 test that replays it against your code. */
public final class TestGenerator {

    private TestGenerator() {
    }

    public static GeneratedTest generate(Recording recording, String packageName) {
        String className = "Bug_" + sanitize(recording.scenario()) + "_" + recording.id() + "Test";
        String resourcePath = "/bugreplay/" + recording.id() + ".json";

        Set<String> dependencies = new LinkedHashSet<>();
        recording.interactions().forEach(i -> dependencies.add(i.dependency()));
        Map<String, String> variables = new LinkedHashMap<>();
        for (String dep : dependencies) {
            variables.put(dep, uniqueVariable(simpleName(dep), variables));
        }

        StringBuilder s = new StringBuilder();
        if (!packageName.isEmpty()) {
            s.append("package ").append(packageName).append(";\n\n");
        }
        s.append("import io.bugreplay.Recording;\n");
        s.append("import io.bugreplay.Replay;\n");
        s.append("import org.junit.jupiter.api.Test;\n\n");
        s.append("/** Generated by bug-replay from recording ").append(recording.id()).append(". */\n");
        s.append("class ").append(className).append(" {\n\n");
        s.append("    @Test\n");
        s.append("    void reproduces_").append(sanitize(recording.scenario())).append("() throws Exception {\n");
        s.append("        Recording recording = Recording.fromResource(\"").append(resourcePath).append("\");\n");
        s.append("        Replay replay = Replay.of(recording);\n\n");
        variables.forEach((dep, var) -> s.append("        ").append(dep.replace('$', '.')).append(' ').append(var)
                .append(" = replay.mock(").append(dep.replace('$', '.')).append(".class);\n"));
        s.append("\n");
        s.append("        // TODO: build the system under test with the mocks above and call it with the\n");
        s.append("        // original input (the recording holds the dependency calls, not the request itself).\n");
        if (recording.failure() == null) {
            s.append("        // No failure was recorded for this request.\n");
        } else {
            s.append("        // Recorded failure: ").append(oneLine(recording.failure().type())).append(": ")
                    .append(oneLine(recording.failure().message())).append("\n");
            s.append("        // assertThrows(").append(recording.failure().type().replace('$', '.'))
                    .append(".class, () -> sut.handle(request));\n");
        }
        s.append("\n        replay.verifyAllConsumed();\n");
        s.append("    }\n}\n");
        return new GeneratedTest(packageName, className, s.toString(), resourcePath);
    }

    /** Writes the recording JSON and the test source into Maven-style test roots. */
    public static GeneratedTest write(Recording recording, String packageName, Path testSourceRoot,
            Path testResourceRoot) {
        GeneratedTest test = generate(recording, packageName);
        try {
            Path dir = packageName.isEmpty() ? testSourceRoot
                    : testSourceRoot.resolve(packageName.replace('.', '/'));
            Files.createDirectories(dir);
            Files.writeString(dir.resolve(test.className() + ".java"), test.source());
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        recording.save(testResourceRoot.resolve(test.resourcePath().substring(1)));
        return test;
    }

    private static String simpleName(String binaryName) {
        String name = binaryName.substring(binaryName.lastIndexOf('.') + 1);
        name = name.substring(name.lastIndexOf('$') + 1);
        return Character.toLowerCase(name.charAt(0)) + name.substring(1);
    }

    private static String uniqueVariable(String base, Map<String, String> used) {
        String candidate = base;
        int n = 2;
        while (used.containsValue(candidate)) {
            candidate = base + n++;
        }
        return candidate;
    }

    private static String sanitize(String text) {
        String cleaned = text.replaceAll("[^A-Za-z0-9]+", "_").replaceAll("^_+|_+$", "");
        if (cleaned.isEmpty()) {
            cleaned = "scenario";
        }
        return Character.isDigit(cleaned.charAt(0)) ? "s" + cleaned : cleaned;
    }

    private static String oneLine(String text) {
        return text == null ? "null" : text.replaceAll("\\s+", " ");
    }
}
